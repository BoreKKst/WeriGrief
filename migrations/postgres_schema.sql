CREATE TABLE economy.wallets (
    user_id BIGINT PRIMARY KEY,
    balance BIGINT NOT NULL DEFAULT 0,
    work_xp BIGINT NOT NULL DEFAULT 0,
    work_level INTEGER NOT NULL DEFAULT 1,
    work_count BIGINT NOT NULL DEFAULT 0,
    total_earned BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE economy.cooldowns (
    user_id BIGINT NOT NULL,
    action TEXT NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (user_id, action)
);

CREATE TABLE economy.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT,
    receiver_id BIGINT,
    amount BIGINT NOT NULL,
    reason TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE pets.pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    co_owner_id BIGINT,
    species TEXT NOT NULL,
    name TEXT NOT NULL,
    level INTEGER NOT NULL DEFAULT 1,
    xp INTEGER NOT NULL DEFAULT 0,
    hunger INTEGER NOT NULL DEFAULT 100,
    mood INTEGER NOT NULL DEFAULT 100,
    created_at DOUBLE PRECISION NOT NULL,
    last_care DOUBLE PRECISION NOT NULL
);

CREATE TABLE pets.pet_inventory (
    user_id BIGINT NOT NULL,
    item TEXT NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, item)
);

CREATE TABLE store.vip_entitlements (
    user_id BIGINT NOT NULL,
    guild_id BIGINT NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (user_id, guild_id)
);

CREATE TABLE playtime.totals (
    nick TEXT PRIMARY KEY,
    seconds BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE playtime.daily (
    nick TEXT NOT NULL,
    day TEXT NOT NULL,
    seconds BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (nick, day)
);

CREATE TABLE playtime.day_status (
    day TEXT PRIMARY KEY,
    reliable BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE playtime.credited_days (
    day TEXT PRIMARY KEY,
    credited_at TEXT NOT NULL
);
